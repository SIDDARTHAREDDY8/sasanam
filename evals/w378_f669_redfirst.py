#!/usr/bin/env python3
"""Red-first for F669: builtin-iterable spread consumption.

Builtin-iterable spread consumption bypasses the decoder: F653 (CLOSED) models custom Symbol.iterator spread/Array.from, and F602 (CLOSED) covers Set for-of/forEach statements, but spread consumption of builtin iterables ([...set], [...map.values()]) has no modeled path; the Array.from builtin twin blocks.
Prints BREAK when a payload MISSES (open tree), HELD when blocked.
"""
import os
import sys

os.environ.setdefault("GOV_DEPLOYMENT_MODE", "staging")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)) + "/..")

from gov.dlp import find_credential  # noqa: E402

# Constructed via concatenation: the write path redacts credential literals.
_A = "xoxb-" + "0123"
_B = "456789" + "abcdef"
_BT = chr(96)

SHAPES = [
    ("set-spread",
     "(function(){var st=new Set(['xoxb-0123','456789abcdef']);return [...st].join('');})()", True),
    ("map-values-spread",
     "(function(){var m=new Map();m.set('a','xoxb-0123');m.set('b','456789abcdef');return [...m.values()].join('');})()", True),
]

CONTROLS = [
    ("array-join-still-blocks",
     "['xoxb-0123','456789abcdef'].join('')", True),
    ("junk-quiet",
     "'(function(){var s=\\'ab\\';return s;})()'", False),
]


def main():
    breaks, held = 0, 0
    for name, payload, recovers in SHAPES:
        hit = find_credential(payload) is not None
        is_break = recovers and not hit
        print("%s: %s" % (name, "BREAK(miss)" if is_break else "HELD(blocks)"))
        if is_break:
            breaks += 1
        else:
            held += 1
    for name, payload, want_hit in CONTROLS:
        hit = find_credential(payload) is not None
        ok = hit == want_hit
        print("%s: %s" % (name, "HELD(control-ok)" if ok else "BREAK(control-bad)"))
        if ok:
            held += 1
        else:
            breaks += 1
    print("tally: %d BREAK / %d HELD" % (breaks, held))
    return 1 if breaks else 0


if __name__ == "__main__":
    sys.exit(main())
