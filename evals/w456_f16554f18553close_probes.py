def _check(name, cases, want_flag):
    bad = []
    for c in cases:
        got = instruction_shaped(c)
        if got != want_flag:
            bad.append((c, got))
    print("%s: %d/%d %s" % (name, len(cases) - len(bad), len(cases),
                            "FLAG" if want_flag else "QUIET"))
    for c, got in bad[:5]:
        print("  MISMATCH %r -> %s" % (c, got))
    return bad


def _stamps():
    path = os.path.join(REPO_ROOT, "evals", "FINDINGS.md")
    lines = open(path).read().split("\n")
    stamped = 0
    missing = []
    for ln in lines:
        m = re.match(r"^\(F(\d+) filed", ln)
        if m and 16554 <= int(m.group(1)) <= 18553:
            if "wave-456 lane C" in ln and "CLOSED" in ln:
                stamped += 1
            else:
                missing.append(int(m.group(1)))
    print("stamps: %d/2000 carry wave-456 lane C CLOSED" % stamped)
    return missing


def _pins():
    dlp = open(os.path.join(REPO_ROOT, "gov", "dlp.py")).read()
    prov = open(os.path.join(REPO_ROOT, "gov",
                             "instruction_provenance.py")).read()
    loops = dlp.count("for _stmtdec in")
    rc_dlp = dlp.count("re.compile(")
    rc_prov = prov.count("re.compile(")
    print("pins: N_STMTDEC_LOOPS=%d (want 203), re.compile dlp=%d (want 29), "  # wave-456 merge: 202 -> 203; wave-456 merge reconciliation: +1 wave-456 lane A dispatch loop = 203
          "prov=%d (want 8)" % (loops, rc_dlp, rc_prov))
    return (loops == 203 and rc_dlp == 29 and rc_prov == 8)  # wave-456 merge: 202 -> 203; wave-456 merge reconciliation: +1 wave-456 lane A dispatch loop = 203


def _green():
    if os.environ.get("GOV_SKIP_GREEN") == "1":
        print("green check: skipped (GOV_SKIP_GREEN=1)")
        return True
    import collections
    byframe = collections.defaultdict(list)
    for c in FILED:
        m = re.match(r"^(.*?) this (.*)$", c)
        byframe[m.group(2)].append(c)
    sample = []
    for f in sorted(byframe):
        # 2 carriers per frame -> find their F-numbers via carrier order
        idxs = [FILED.index(c) for c in byframe[f][:2]]
        sample.extend(idxs)
    ok = True
    for idx in sorted(sample):
        n = 16554 + idx
        bat = os.path.join(REPO_ROOT, "evals",
                           "w455_f%d_redfirst.py" % n)
        env = dict(os.environ)
        env["GOV_SKIP_GREEN"] = "1"
        r = subprocess.run([sys.executable, bat], capture_output=True,
                           text=True, timeout=180, env=env)
        held = "HELD" in r.stdout
        if not held:
            ok = False
            print("  green FAIL F%d: %s" % (n, r.stdout.strip()[-200:]))
    print("green check: %d sampled red-first batteries %s"
          % (len(sample), "all HELD" if ok else "FAILURES"))
    return ok


