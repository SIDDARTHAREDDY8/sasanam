    fails = 0
    t0 = time.time()
    fails += len(_check("filed FLAG", FILED, True))
    dt = time.time() - t0
    print("perf: %.1f ms/call in-process (2000 carriers)"
          % (dt * 1000.0 / len(FILED)))
    fails += len(_check("it-form FLAG", IT_FORM, True))
    fails += len(_check("of-guard QUIET", OF_GUARD, False))
    fails += len(_check("bounds QUIET", BOUNDS_QUIET, False))
    fails += len(_check("pre-existing FLAG", PREEXISTING_FLAG, True))
    fails += len(_check("sibling pins FLAG", SIBLING_PINS, True))
    fails += len(_stamps())
