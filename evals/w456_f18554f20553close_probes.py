def main():
    fails = 0
    for n in sorted(CARRIERS):
        v = "FLAG" if instruction_shaped(CARRIERS[n]) else "QUIET"
        if v != "FLAG":
            print("FAIL carrier F%d: got %s" % (n, v))
            fails += 1
    for text, exp in CONTROLS:
        v = "FLAG" if instruction_shaped(text) else "QUIET"
        if v != exp:
            print("FAIL control %r: got %s, want %s" % (text, v, exp))
            fails += 1
    for text, exp in BOUNDS:
        v = "FLAG" if instruction_shaped(text) else "QUIET"
        if v != exp:
            print("FAIL bound %r: got %s, want %s" % (text, v, exp))
            fails += 1
    for n, text, exp in SIBLINGS:
        v = "FLAG" if instruction_shaped(text) else "QUIET"
        if v != exp:
            print("FAIL sibling F%d: got %s, want %s" % (n, v, exp))
            fails += 1
    # Pins.
    dlp = open(os.path.join(REPO_ROOT, "gov", "dlp.py")).read()
    prov = open(os.path.join(REPO_ROOT, "gov", "instruction_provenance.py")).read()
    loops = dlp.count("for _stmtdec in")
    if loops != 203:  # wave-456 merge: 202 -> 203; wave-456 merge reconciliation: +1 wave-456 lane A dispatch loop = 203
        print("FAIL pin N_STMTDEC_LOOPS: got %d want 203" % loops)  # wave-456 merge: 202 -> 203; wave-456 merge reconciliation: +1 wave-456 lane A dispatch loop = 203
        fails += 1
    if dlp.count("re.compile(") != 29:
        print("FAIL pin re.compile dlp: got %d want 29" % dlp.count("re.compile("))
        fails += 1
    if prov.count("re.compile(") != 8:
        print("FAIL pin re.compile prov: got %d want 8" % prov.count("re.compile("))
        fails += 1
    # Stamps.
    findings = open(os.path.join(REPO_ROOT, "evals", "FINDINGS.md")).read().split("\n")
    by_n = {}
    for ln in findings:
        m = re.match(r"^\(F(\d+) filed", ln)
        if m:
            by_n[int(m.group(1))] = ln
    for n in sorted(CARRIERS):
        ln = by_n.get(n, "")
        if "wave-456 lane D" not in ln or "CLOSED" not in ln:
            print("FAIL stamp F%d" % n)
            fails += 1
    # Perf (in-process).
    t0 = time.time()
    for n in sorted(CARRIERS):
        instruction_shaped(CARRIERS[n])
    dt = (time.time() - t0) / len(CARRIERS) * 1000.0
    print("perf: %.2f ms/call in-process (%d carriers)" % (dt, len(CARRIERS)))
    if dt > 200.0:
        print("FAIL perf: %.2f ms/call > 200" % dt)
        fails += 1
    # Green check: sampled per-finding red-first batteries, expect HELD.
    if os.environ.get("GOV_SKIP_GREEN") == "1":
        print("green check skipped (GOV_SKIP_GREEN=1)")
    else:
        genv = dict(os.environ)
        gtmp = os.path.join("/tmp", "g456D-green")
        os.makedirs(gtmp, exist_ok=True)
        genv["TMPDIR"] = gtmp
        genv["GOV_SKIP_GREEN"] = "1"
        held = 0
        for n in GREEN_SAMPLE:
            path = os.path.join(REPO_ROOT, "evals", "w455_f%d_redfirst.py" % n)
            r = subprocess.run([sys.executable, path], capture_output=True,
                               text=True, timeout=180, env=genv)
            if "HELD" in r.stdout:
                held += 1
            else:
                print("FAIL green F%d: %r" % (n, (r.stdout or "")[-200:]))
                fails += 1
        print("green check: %d/%d HELD" % (held, len(GREEN_SAMPLE)))
    total = len(CARRIERS) + len(CONTROLS) + len(BOUNDS) + len(SIBLINGS) + 3 + len(CARRIERS)
    print("%d/%d PASS" % (total - fails, total))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
