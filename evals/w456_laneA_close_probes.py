def _entry_status(block_lines):
    text = "\n".join(block_lines)
    first = block_lines[0] if block_lines else ""
    if "[CLOSED" in first.split(";")[0]:
        return "CLOSED"
    if "**Status: CLOSED" in text:
        return "CLOSED"
    for sev in ("LOW", "MEDIUM", "HIGH", "CRITICAL"):
        if sev + ", CLOSED" in text or sev + ", [CLOSED" in text:
            return "CLOSED"
    if "; CLOSED " in text or "OPEN: [CLOSED" in text:
        return "CLOSED"
    if "OPEN" in text:
        return "OPEN"
    return "UNKNOWN"


