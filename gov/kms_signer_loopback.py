#!/usr/bin/env python3
"""Loopback KMS: the local test/dev reference signer. NEVER a
production KMS substitute.

This module simulates the KMS-resident signing discipline with
zero network and zero credentials: key material (Ed25519 seeds /
HMAC keys) is generated by the algorithm registry and held
inside the ``LoopbackKms`` instance — the "KMS boundary" — and no
public method ever returns it. ``sign`` returns signatures only;
``public_key_for`` returns the public half (or, for MAC tiers,
the shared authentication key, which callers must treat as
secret).

Honest limits (this is a TEST DOUBLE, not a KMS):

* The keys live in process memory, not in hardware; a process
  compromise yields them. It provides **zero** production
  custody guarantees.
* It exercises the ``KmsSigner`` protocol (key-ref validation,
  message bound, algorithm dispatch, honest tier labeling) so
  batteries and deployments can test their *use* of the
  protocol without a real KMS.
* Production wiring is operator-owned: a real Vault/OpenBao
  (transit) or cloud-KMS adapter implementing the
  ``KmsSigner`` surface — this module is never that.

Re-derived for this repo; no upstream design text copied.
Stdlib only. No network. $0.
"""

from .kms_signer import KeyRef, KmsSigner, KmsSignerError


class LoopbackKms(KmsSigner):
    """A local KMS-resident signer reference implementation.

    ``provision_key(provider, key_id, algorithm)`` mints a fresh
    key inside the loopback and returns a :class:`KeyRef` for it.
    The private material stays in the instance's private store —
    it is never returned, serialized, or logged by any method of
    this class. Only signatures (and, per the protocol, public
    keys) cross the boundary.

    ``registry`` may be supplied for testing against a custom
    ``AlgorithmRegistry``; otherwise the shared default registry
    is used.
    """

    def __init__(self, registry=None):
        super().__init__(registry=registry)
        self._store = {}  # (provider, key_id) -> _Provisioned

    def provision_key(self, provider, key_id, algorithm):
        """Mint a fresh key inside the loopback; return its
        :class:`KeyRef`. The private material never leaves."""
        ref = KeyRef(provider, key_id, algorithm)
        self._validate_key_ref(ref)  # algorithm known, fail closed
        seed, public = self._registry.keygen(algorithm)
        self._store[(provider, key_id)] = _Provisioned(ref, seed, public)
        return ref

    def key_ids(self):
        """Metadata only: the provisioned (provider, key_id) pairs.
        No key material."""
        return sorted(self._store.keys())

    def _lookup(self, key_ref):
        try:
            return self._store[(key_ref.provider, key_ref.key_id)]
        except KeyError:
            raise KmsSignerError(
                "kms-signer-refused: unknown key id %r under provider %r"
                % (key_ref.key_id, key_ref.provider))

    # -- KmsSigner backend surface -----------------------------------

    def _backend_sign(self, key_ref, message):
        # The private material is read HERE, inside the loopback,
        # and only signature bytes return.
        provisioned = self._lookup(key_ref)
        return self._registry.sign(key_ref.algorithm, message,
                                   provisioned.secret)

    def _public_key_for(self, key_ref):
        return self._lookup(key_ref).public


class _Provisioned:
    """One loopback-held key. Private to this module: not exported,
    and the ``LoopbackKms`` public API never returns one."""

    __slots__ = ("ref", "secret", "public")

    def __init__(self, ref, secret, public):
        self.ref = ref
        self.secret = secret
        self.public = public
